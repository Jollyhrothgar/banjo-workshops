#!/usr/bin/env python3
"""Decode an iVocalize "presentation.bin" recording into a timed event list.

This is how data/session.js was produced from the original 2006 export
(BanjoLoungeChat_200610171904/presentation.bin). The original export is not
kept in this repository; the script is here as a record of how the format was
decoded, and so the data can be regenerated if the source turns up again.

Usage:
    python3 tools/extract_session.py path/to/presentation.bin > data/session.js

File format (reverse engineered; all integers big-endian unless noted):

    u16 len + "iVocalize Presentation"     header string (Java writeUTF)
    9 bytes                                 header fields (not needed)
    then records until EOF:
        u8  type
        u16 length
        length bytes of payload

Record types:
    1  audio packet. Each one holds 240 ms of audio. Recordings carry no
       timestamps, so an event's time is (audio packets seen so far) * 0.24 s.
       The 44,768 packets in this recording give 10,744.32 s, which matches the
       exported presentation.mp3 exactly.
    2  chat line: "\\r\\n[name] message\\r\\n"
    3  current speaker (who holds the microphone): name
    4  web page pushed to viewers: "^" + URL
    5  whiteboard drawing command (see parse_draw)
    6  slide change: "img/sN.jpg", or empty to clear the whiteboard
"""
import json
import struct
import sys

PACKET_SECONDS = 0.24


def nib(v):
    """Signed 4-bit value."""
    return v - 16 if v > 7 else v


def parse_draw(pl):
    """Whiteboard commands. Fields after the 4-byte prefix are little-endian.

    prefix: u16le 6, u16le body length
    body:   u8 cmd, u8 style, u16le object id, 4 x u16le (x1,y1,x2,y2),
            4 bytes pen (colour/width; not fully decoded), then per-command data.
      cmd 0x0a line     from (x1,y1) to (x2,y2)
      cmd 0x0c text     box (x1,y1,x2,y2); u8 size, u8 flags, font\\0, text\\0
      cmd 0x0d freehand bbox; u16le start x, start y; then one byte per step,
                        high nibble = dy, low nibble = dx (signed)
      cmd 0x0e delete   object id
    """
    cmd, style, oid = pl[4], pl[5], struct.unpack_from('<H', pl, 6)[0]
    x1, y1, x2, y2 = struct.unpack_from('<4H', pl, 8)
    rest = pl[20:]
    if cmd == 0x0a:
        return {'op': 'line', 'id': oid, 'pts': [[x1, y1], [x2, y2]]}
    if cmd == 0x0e:
        return {'op': 'delete', 'id': oid}
    if cmd == 0x0c:
        size, flags = rest[0], rest[1]
        font, text = rest[2:].split(b'\0')[:2]
        return {'op': 'text', 'id': oid, 'x': x1, 'y': y1, 'size': size,
                'bold': bool(flags & 0x80), 'font': font.decode('latin1'),
                'text': text.decode('latin1')}
    if cmd == 0x0d:
        x, y = struct.unpack_from('<2H', rest, 0)
        pts = [[x, y]]
        for b in rest[4:]:
            y += nib(b >> 4)
            x += nib(b & 15)
            pts.append([x, y])
        return {'op': 'path', 'id': oid, 'pts': pts, 'bbox': [x1, y1, x2, y2]}
    return {'op': 'unknown', 'cmd': cmd, 'raw': pl.hex()}


def decode(data):
    (hlen,) = struct.unpack_from('>H', data, 0)
    assert data[2:2 + hlen] == b'iVocalize Presentation', 'not an iVocalize recording'
    p = 2 + hlen + 9
    packets = 0
    events = []
    while p < len(data):
        t = data[p]
        (ln,) = struct.unpack_from('>H', data, p + 1)
        pl = data[p + 3:p + 3 + ln]
        p += 3 + ln
        ts = round(packets * PACKET_SECONDS, 2)
        if t == 1:
            packets += 1
        elif t == 2:
            line = pl.decode('utf-8', 'replace').strip()
            name, _, msg = line[1:].partition('] ')
            events.append({'t': ts, 'type': 'chat', 'name': name, 'text': msg.strip()})
        elif t == 3:
            events.append({'t': ts, 'type': 'speaker', 'name': pl.decode('latin1')})
        elif t == 4:
            events.append({'t': ts, 'type': 'web', 'url': pl.decode('latin1').lstrip('^')})
        elif t == 5:
            events.append({'t': ts, 'type': 'draw', **parse_draw(pl)})
        elif t == 6:
            events.append({'t': ts, 'type': 'slide', 'src': pl.decode('latin1') or None})
        else:
            raise ValueError(f'unknown record type {t} at offset {p}')
    return {'duration': round(packets * PACKET_SECONDS, 2), 'events': events}


def main():
    session = decode(open(sys.argv[1], 'rb').read())
    for e in session['events']:
        if e['type'] == 'draw' and e['op'] == 'path':
            xs = [q[0] for q in e['pts']]
            ys = [q[1] for q in e['pts']]
            b = e.pop('bbox')
            assert b == [min(xs), min(ys), max(xs), max(ys)], f"stroke {e['id']} off its bbox"
    sys.stdout.write('// Generated by tools/extract_session.py from the 2006 iVocalize recording.\n')
    sys.stdout.write('window.SESSION = ')
    json.dump(session, sys.stdout, separators=(',', ':'), ensure_ascii=False)
    sys.stdout.write(';\n')


if __name__ == '__main__':
    main()
